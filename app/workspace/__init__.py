"""Workspace 域：工作区读取、写入与本地文件操作。

**应用内一等公民域**（不是可复用包）：强依赖 Redis / DB / 客户端 MCP / settings。

读 / 写按方案要求落成**子包边界**——这也是本域最重要的一条纪律：

```text
app/workspace/
├─ service.py     工作区本体：创建 / 列出 / 删除 / 设备与会话绑定
├─ context.py     上下文：权限画像、能力可见性、健康探测（读写都用）
├─ read/          只读一侧
│   navigator     目录/文件读取与检索（list / search / read / scan 四个 handler）
│   reader        统一分段文本投影（大文件按段读）
└─ write/         写入一侧
    operations    暂存 / 提交 / 删除等写操作（客户端与导航器两种 client）
    revision      修订与比对（文本/目录修订值、换行策略、单次替换）
    trash         回收站（记录、配额、恢复、过期）
```

**为什么读写要分开**：读路径要尽可能宽（先读才能改），写路径要尽可能窄（每个写操作
都要过写闸、修订校验、回收站）。混在一个模块里时，"加一个读能力"和"加一个写能力"
看起来一样，评审时看不出风险差别；分成两个子包之后，review 的默认预期就不同了。

``navigator``（2447 行）内部**全是读**、``operations``（1699 行）内部**全是写**，
所以这一刀落在模块边界上；两个大文件内部各自的段标（handler 分组 / 操作分组）
写在文件里，进一步的内部拆分留到需要时再做（拆分本身不改行为，但没有收益时不做）。

**没有兼容层**：这 7 个模块过去是各自被 import 的（没有聚合入口），
所以"旧路径 → 新路径"是一次干净迁移（全部调用点已改），不留转发壳——
白名单只减不增，参见 ``tools/compat_shims.txt``。
"""
